export const SocialLinks: React.FC<SocialLinksProps> = ({ links }) => {
  if (!links || Object.keys(links).length === 0) return null;

  return (
    <div style={{ display: 'flex', flexWrap: 'wrap', gap: 10, justifyContent: 'center', marginTop: 15 }}>
      {Object.entries(links).map(([key, url]) => {
        if (!url) return null;
        const config = SOCIAL_CONFIG[key];
        if (!config) return null;

        return (
          <a
            key={key}
            href={url}
            target="_blank"
            rel="noopener noreferrer"
            title={config.label}
            style={{
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
              width: 36,
              height: 36,
              borderRadius: '50%',
              background: `${config.color}15`,
              border: `1px solid ${config.color}40`,
              color: config.color,
              transition: 'all 0.2s ease',
            }}
            onMouseEnter={(e) => {
              e.currentTarget.style.background = config.color;
              e.currentTarget.style.color = '#000';
            }}
            onMouseLeave={(e) => {
              e.currentTarget.style.background = `${config.color}15`;
              e.currentTarget.style.color = config.color;
            }}
          >
            {config.icon}
          </a>
        );
      })}
    </div>
  );
};